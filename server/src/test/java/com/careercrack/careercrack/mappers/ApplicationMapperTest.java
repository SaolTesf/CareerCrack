package com.careercrack.careercrack.mappers;

import com.careercrack.careercrack.dtos.ApplicationRequest;
import com.careercrack.careercrack.dtos.ApplicationResponse;
import com.careercrack.careercrack.dtos.ApplicationSummaryResponse;
import com.careercrack.careercrack.dtos.ContactResponse;
import com.careercrack.careercrack.enums.ApplicationStatus;
import com.careercrack.careercrack.enums.SalaryPeriod;
import com.careercrack.careercrack.models.Company;
import com.careercrack.careercrack.models.Contact;
import com.careercrack.careercrack.models.ImportJob;
import com.careercrack.careercrack.models.JobApplication;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.test.context.junit.jupiter.SpringJUnitConfig;

import static org.assertj.core.api.Assertions.assertThat;

/** Builds just the mappers (no database, no web server): the *Impl classes are generated by MapStruct. */
@SpringJUnitConfig(classes = {ApplicationMapperImpl.class, CompanyMapperImpl.class, ContactMapperImpl.class, StatusHistoryMapperImpl.class})
class ApplicationMapperTest {

    @Autowired
    private ApplicationMapper mapper;

    private static ApplicationRequest request() {
        ApplicationRequest request = new ApplicationRequest();
        request.setCompanyId(3L);
        request.setRoleTitle("  Backend Engineer ");
        return request;
    }

    private static Company company(Long id, String name) {
        Company company = new Company();
        company.setId(id);
        company.setName(name);
        return company;
    }

    private static Contact contact(Long id, String name, Company company) {
        Contact contact = new Contact();
        contact.setId(id);
        contact.setName(name);
        contact.setCompany(company);
        return contact;
    }

    // ---- request to entity ----

    @Test
    void toEntityTrimsTextStoresBlankAsNullAndFillsTheSalaryDefaults() {
        ApplicationRequest request = request();
        request.setLocation("   ");
        request.setNotes("  keep this  ");

        JobApplication entity = mapper.toEntity(request);

        assertThat(entity.getRoleTitle()).isEqualTo("Backend Engineer");
        assertThat(entity.getLocation()).isNull();
        assertThat(entity.getNotes()).isEqualTo("keep this");
        assertThat(entity.getSalaryCurrency()).isEqualTo("USD");
        assertThat(entity.getSalaryPeriod()).isEqualTo(SalaryPeriod.YEARLY);
    }

    @Test
    void toEntityUpperCasesTheCurrencyAndKeepsTheSalaryPeriod() {
        ApplicationRequest request = request();
        request.setSalaryCurrency("eur");
        request.setSalaryPeriod(SalaryPeriod.HOURLY);

        JobApplication entity = mapper.toEntity(request);

        assertThat(entity.getSalaryCurrency()).isEqualTo("EUR");
        assertThat(entity.getSalaryPeriod()).isEqualTo(SalaryPeriod.HOURLY);
    }

    @Test
    void toEntityLeavesTheOwnerCompanyStageAndPositionToTheService() {
        ApplicationRequest request = request();
        request.setStatus(ApplicationStatus.APPLIED);

        JobApplication entity = mapper.toEntity(request);

        assertThat(entity.getId()).isNull();
        assertThat(entity.getUser()).isNull();
        assertThat(entity.getCompany()).isNull();
        assertThat(entity.getStatus()).isEqualTo(ApplicationStatus.BOOKMARKED);
        assertThat(entity.getSortOrder()).isEqualTo(0);
    }

    @Test
    void updateEntityReplacesEveryFieldSoNullsClearThem() {
        JobApplication existing = new JobApplication();
        existing.setId(5L);
        existing.setStatus(ApplicationStatus.INTERVIEWING);
        existing.setSortOrder(3);
        existing.setLocation("Austin, TX");
        existing.setNotes("old notes");
        existing.setSalaryCurrency("EUR");

        mapper.updateEntity(request(), existing);

        assertThat(existing.getRoleTitle()).isEqualTo("Backend Engineer");
        assertThat(existing.getLocation()).isNull();
        assertThat(existing.getNotes()).isNull();
        assertThat(existing.getSalaryCurrency()).isEqualTo("USD");
        // the id, stage and position are not the request's to change
        assertThat(existing.getId()).isEqualTo(5L);
        assertThat(existing.getStatus()).isEqualTo(ApplicationStatus.INTERVIEWING);
        assertThat(existing.getSortOrder()).isEqualTo(3);
    }

    // ---- entity to response ----

    @Test
    void toSummaryFlattensTheCompany() {
        JobApplication application = new JobApplication();
        application.setId(5L);
        application.setCompany(company(3L, "Acme"));
        application.setRoleTitle("Backend Engineer");
        application.setStatus(ApplicationStatus.APPLIED);

        ApplicationSummaryResponse summary = mapper.toSummary(application);

        assertThat(summary.getId()).isEqualTo(5L);
        assertThat(summary.getCompanyId()).isEqualTo(3L);
        assertThat(summary.getCompanyName()).isEqualTo("Acme");
        assertThat(summary.getStatus()).isEqualTo(ApplicationStatus.APPLIED);
    }

    @Test
    void toDetailIncludesCompanyContactsAndHistoryButLeavesEventsAndDocumentsEmpty() {
        Company acme = company(3L, "Acme");
        ImportJob importJob = new ImportJob();
        importJob.setId(8L);
        JobApplication application = new JobApplication();
        application.setId(5L);
        application.setCompany(acme);
        application.setImportJob(importJob);
        application.setRoleTitle("Backend Engineer");
        application.setJobDescription("Build APIs");
        application.setStatus(ApplicationStatus.APPLIED);
        application.addContact(contact(2L, "zed", acme));
        application.addContact(contact(1L, "Anna", acme));
        application.recordInitialStatus();

        ApplicationResponse detail = mapper.toDetail(application);

        assertThat(detail.getCompanyName()).isEqualTo("Acme");
        assertThat(detail.getCompany().getName()).isEqualTo("Acme");
        assertThat(detail.getJobDescription()).isEqualTo("Build APIs");
        assertThat(detail.getImportJobId()).isEqualTo(8L);
        assertThat(detail.getContacts()).extracting(ContactResponse::getName).containsExactly("Anna", "zed");
        assertThat(detail.getStatusHistory()).hasSize(1);
        assertThat(detail.getEvents()).isEmpty();
        assertThat(detail.getDocuments()).isEmpty();
    }
}
