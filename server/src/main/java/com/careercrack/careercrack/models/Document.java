package com.careercrack.careercrack.models;

import com.careercrack.careercrack.enums.DocumentType;
import jakarta.persistence.*;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.PositiveOrZero;
import jakarta.validation.constraints.Size;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;

import java.time.LocalDateTime;

/**
 * One specific version of a resume or cover letter. The file lives outside the database; storageKey says where.
 * (user, docType, name, version) is unique, so uploading "Backend resume" again means version 2.
 */
@Entity
@Getter
@Setter
@NoArgsConstructor
@Table(name = "documents", schema = "careercrack")
public class Document {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", updatable = false)
    private Long id;

    @NotNull(message = "User is required")
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false, updatable = false)
    private User user;

    @NotNull(message = "Document type is required")
    @Enumerated(EnumType.STRING)
    @Column(name = "doc_type", nullable = false, length = 20)
    private DocumentType docType;

    // what the user calls it, e.g. "Backend resume"
    @NotBlank(message = "Document name is required")
    @Size(max = 255, message = "Document name must be at most 255 characters")
    @Column(name = "name", nullable = false, length = 255)
    private String name;

    @NotNull
    @Min(value = 1, message = "Version must be at least 1")
    @Column(name = "version", nullable = false)
    private Integer version = 1;

    @NotBlank(message = "File name is required")
    @Size(max = 255, message = "File name must be at most 255 characters")
    @Column(name = "file_name", nullable = false, length = 255)
    private String fileName;

    @Size(max = 100, message = "Content type must be at most 100 characters")
    @Column(name = "content_type", length = 100)
    private String contentType;

    @PositiveOrZero(message = "File size cannot be negative")
    @Column(name = "file_size")
    private Long fileSize;

    // generated by the server, never taken from a request (a client-supplied path could point anywhere on disk)
    @NotBlank(message = "Storage key is required")
    @Column(name = "storage_key", nullable = false, columnDefinition = "TEXT")
    private String storageKey;

    // what changed in this version
    @Size(max = 5000, message = "Notes must be at most 5000 characters")
    @Column(name = "notes", columnDefinition = "TEXT")
    private String notes;

    @CreationTimestamp
    @Column(name = "created_at", updatable = false)
    private LocalDateTime createdAt;

    // documents sit in a Set on JobApplication, so equality is by id (two unsaved documents are never equal)
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Document other)) return false;
        return id != null && id.equals(other.getId());
    }

    @Override
    public int hashCode() {
        return Document.class.hashCode();
    }
}
